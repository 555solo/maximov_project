# Задача 3: Конвертер температур
# ===== ИСХОДНЫЕ ДАННЫЕ =====
celsius = -5  # температура в градусах Цельсия

# ===== РАСЧЕТЫ =====
# Перевод в Фаренгейты
fahrenheit = celsius * 9/5 + 32

# Определение состояния воды
if celsius <= 0:
    state = "Лёд"
elif celsius < 100:
    state = "Жидкость"
else:
    state = "Пар"

# ===== ВЫВОД РЕЗУЛЬТАТОВ =====
print("=" * 40)
print("КОНВЕРТЕР ТЕМПЕРАТУР")
print("=" * 40)
print(f"Температура: {celsius}°C")
print(f"В Фаренгейтах: {fahrenheit:.1f}°F")
print(f"Состояние воды: {state}")
print("=" * 40)