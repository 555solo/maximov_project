# Задача 4: Рабочий график
# ===== ИСХОДНЫЕ ДАННЫЕ =====
day_number = 6  # номер дня (1 = понедельник, 7 = воскресенье)

# ===== ОПРЕДЕЛЕНИЕ ДНЯ НЕДЕЛИ =====
days = {
    1: "Понедельник",
    2: "Вторник",
    3: "Среда",
    4: "Четверг",
    5: "Пятница",
    6: "Суббота",
    7: "Воскресенье"
}

# ===== ОПРЕДЕЛЕНИЕ РЕЖИМА РАБОТЫ =====
if day_number < 1 or day_number > 7:
    print("Ошибка: номер дня должен быть от 1 до 7!")
else:
    day_name = days[day_number]

    if day_number <= 5:
        work_status = "Рабочий день"
        schedule = "8:00 - начало смены"
    else:
        work_status = "Выходной"
        schedule = "Отдых"

    # ===== ВЫВОД РЕЗУЛЬТАТОВ =====
    print("=" * 40)
    print("РАБОЧИЙ ГРАФИК")
    print("=" * 40)
    print(f"Номер дня: {day_number}")
    print(f"День недели: {day_name}")
    print(f"Статус: {work_status}")
    print(f"Режим: {schedule}")
    print("=" * 40)